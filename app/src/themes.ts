/**
 * Slumpar fram ett givet antal unika föremål ur den valda kategorin och svårighetsgraden.
 */
export function drawRandomTiles(
  categoryId: string = 'city',
  difficulty: Difficulty = 'easy',
  count: number = 9
): ThemeItem[] {
  const category = THEME_CATEGORIES.find(c => c.id === categoryId) || THEME_CATEGORIES[0];
  const pool = category.difficulties[difficulty]?.items || category.difficulties.easy.items;

  // Blanda med Fisher-Yates shuffle
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, count);
}
